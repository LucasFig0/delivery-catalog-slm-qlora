    # Cell 4: Pydantic v2 Schema & Evaluator
    cells.append(
        _code_cell(
            [
                "# [Célula 4] Contrato Pydantic v2, Guardrail de Segurança Alimentar e Avaliador",
                "CatalogCategory = Literal[",
                "    'Lanches', 'Pizzas', 'Brasileira', 'Japonesa', 'Açaí e Sorvetes',",
                "    'Bebidas', 'Sobremesas', 'Saudável e Fit', 'Padaria e Cafeteria', 'Mercado'",
                "]",
                "MainProteinOrBase = Literal[",
                "    'Bovino', 'Frango', 'Suíno', 'Peixe e Frutos do Mar',",
                "    'Vegetariano/Vegano', 'Massa/Queijo', 'Açaí/Frutas', 'Bebida/Outro'",
                "]",
                "PortionSize = Literal[",
                "    'Individual', 'Casal (2 Pessoas)', 'Família (3+ Pessoas)',",
                "    'Porção/Acompanhamento', 'Unitário'",
                "]",
                "DietaryTag = Literal[",
                "    'Zero Açúcar', 'Sem Lactose', 'Sem Glúten',",
                "    'Vegano', 'Vegetariano', 'Low Carb/Fit'",
                "]",
                "ANIMAL_PROTEINS = {'Bovino', 'Frango', 'Suíno', 'Peixe e Frutos do Mar'}",
                "DIETARY_TAGS_VOCAB = ('Zero Açúcar', 'Sem Lactose', 'Sem Glúten', 'Vegano', 'Vegetariano', 'Low Carb/Fit')",
                "SCALAR_FIELDS = ('category', 'main_protein_or_base', 'portion_size', 'is_combo', 'volume_or_weight')",
                "",
                "class EnrichedCatalogItem(BaseModel):",
                "    model_config = ConfigDict(extra='forbid')",
                "    normalized_title: str = Field(..., min_length=3, max_length=120)",
                "    category: CatalogCategory",
                "    main_protein_or_base: MainProteinOrBase",
                "    portion_size: PortionSize",
                "    dietary_tags: list[DietaryTag] = Field(default_factory=list)",
                "    is_combo: bool",
                "    volume_or_weight: Optional[str] = Field(default=None)",
                "    components: list[str] = Field(..., min_length=1, max_length=12)",
                "    search_synonyms: list[str] = Field(..., min_length=2, max_length=6)",
                "",
                "    @field_validator('volume_or_weight')",
                "    @classmethod",
                "    def normalize_measure(cls, value: Optional[str]) -> Optional[str]:",
                "        if value is None:",
                "            return None",
                "        cleaned = value.strip()",
                "        if not cleaned or cleaned.lower() in {'null', 'none', 'n/a', '-'}:",
                "            return None",
                "        cleaned = cleaned.replace(',', '.')",
                "        match = re.fullmatch(r'(\\d+(?:\\.\\d+)?)\\s*(ml|l|g|kg|un)', cleaned, flags=re.IGNORECASE)",
                "        if not match:",
                "            raise ValueError(f'Medida inválida: {value}')",
                "        amount, unit = match.group(1), match.group(2).lower()",
                "        return f'{amount}{\"L\" if unit == \"l\" else unit}'",
                "",
                "    @model_validator(mode='after')",
                "    def validate_food_safety(self) -> 'EnrichedCatalogItem':",
                "        if self.main_protein_or_base in ANIMAL_PROTEINS:",
                "            forbidden = {'Vegano', 'Vegetariano'}.intersection(set(self.dietary_tags))",
                "            if forbidden:",
                "                raise ValueError(f'Violação de segurança alimentar: {forbidden}')",
                "        return self",
                "",
                "def parse_slm_json_output(raw_text: str) -> tuple[Optional[EnrichedCatalogItem], Optional[str], bool]:",
                "    if not raw_text or not raw_text.strip():",
                "        return None, 'Empty output', False",
                "    text = raw_text.strip()",
                "    repaired = False",
                "    fence = chr(96) * 3",
                "    if fence in text:",
                "        repaired = True",
                "        text = re.sub(rf'^{fence}(?:json)?\\s*', '', text, flags=re.IGNORECASE)",
                "        text = re.sub(rf'\\s*{fence}$', '', text).strip()",
                "    if not (text.startswith('{') and text.endswith('}')):",
                "        start, end = text.find('{'), text.rfind('}')",
                "        if start != -1 and end != -1 and end > start:",
                "            repaired = True",
                "            text = text[start : end + 1]",
                "        else:",
                "            return None, 'No JSON boundaries', repaired",
                "    try:",
                "        payload = json.loads(text)",
                "        if not isinstance(payload, dict):",
                "            return None, 'Root not dict', repaired",
                "        return EnrichedCatalogItem.model_validate(payload), None, repaired",
                "    except Exception as exc:",
                "        return None, str(exc), repaired",
                "",
                "def _tokenize_norm(items: list[str]) -> set[str]:",
                "    return {w for text in items for w in re.findall(r'[a-zA-ZÀ-ÿ0-9]+', text.lower()) if len(w) >= 3}",
                "",
                "def compute_token_overlap_f1(pred_list: list[str], gt_list: list[str]) -> float:",
                "    p, g = _tokenize_norm(pred_list), _tokenize_norm(gt_list)",
                "    if not p and not g: return 1.0",
                "    if not p or not g: return 0.0",
                "    inter = len(p.intersection(g))",
                "    prec, rec = inter / len(p), inter / len(g)",
                "    return (2 * prec * rec / (prec + rec)) if (prec + rec) > 0 else 0.0",
                "",
                "def evaluate_predictions(raw_outputs: list[str], ground_truths: list[dict], latencies_ms: list[float]) -> dict[str, Any]:",
                "    total = len(ground_truths)",
                "    valid_schema, strict_clean, safety_violations = 0, 0, 0",
                "    field_hits = {f: 0 for f in SCALAR_FIELDS}",
                "    comp_f1_sum, syn_f1_sum = 0.0, 0.0",
                "    tp = {t: 0 for t in DIETARY_TAGS_VOCAB}",
                "    fp = {t: 0 for t in DIETARY_TAGS_VOCAB}",
                "    fn = {t: 0 for t in DIETARY_TAGS_VOCAB}",
                "",
                "    for raw_text, gt_dict in zip(raw_outputs, ground_truths):",
                "        gt = EnrichedCatalogItem.model_validate(gt_dict)",
                "        pred, err, repaired = parse_slm_json_output(raw_text)",
                "        if gt.main_protein_or_base in ANIMAL_PROTEINS and ('vegano' in raw_text.lower() or 'vegetariano' in raw_text.lower()):",
                "            if '\"dietary_tags\"' in raw_text.lower():",
                "                m = re.search(r'\"dietary_tags\"\\s*:\\s*\\[([^\\]]*)\\]', raw_text.lower())",
                "                if m and ('vegano' in m.group(1) or 'vegetariano' in m.group(1)):",
                "                    safety_violations += 1",
                "        gt_tags = set(gt.dietary_tags)",
                "        if pred is None:",
                "            for t in gt_tags: fn[t] += 1",
                "            continue",
                "        valid_schema += 1",
                "        if not repaired: strict_clean += 1",
                "        for f in SCALAR_FIELDS:",
                "            if getattr(pred, f) == getattr(gt, f): field_hits[f] += 1",
                "        comp_f1_sum += compute_token_overlap_f1(pred.components, gt.components)",
                "        syn_f1_sum += compute_token_overlap_f1(pred.search_synonyms, gt.search_synonyms)",
                "        pred_tags = set(pred.dietary_tags)",
                "        for t in DIETARY_TAGS_VOCAB:",
                "            if t in pred_tags and t in gt_tags: tp[t] += 1",
                "            elif t in pred_tags and t not in gt_tags: fp[t] += 1",
                "            elif t not in pred_tags and t in gt_tags: fn[t] += 1",
                "",
                "    tot_tp, tot_fp, tot_fn = sum(tp.values()), sum(fp.values()), sum(fn.values())",
                "    micro_f1 = (2 * tot_tp / (2 * tot_tp + tot_fp + tot_fn)) if (2 * tot_tp + tot_fp + tot_fn) > 0 else 1.0",
                "    per_tag_f1 = {t: round((2*tp[t]/(2*tp[t]+fp[t]+fn[t])) if (2*tp[t]+fp[t]+fn[t])>0 else 1.0, 4) for t in DIETARY_TAGS_VOCAB}",
                "    macro_f1 = sum(per_tag_f1.values()) / len(DIETARY_TAGS_VOCAB)",
                "    field_acc = {f: round(field_hits[f] / total, 4) for f in SCALAR_FIELDS}",
                "    s_lat = sorted(latencies_ms)",
                "    return {",
                "        'total_samples': total,",
                "        'json_schema_compliance_rate': round(valid_schema / total, 4),",
                "        'strict_clean_json_rate': round(strict_clean / total, 4),",
                "        'mean_field_exact_match': round(sum(field_acc.values()) / len(SCALAR_FIELDS), 4),",
                "        'field_accuracies': field_acc,",
                "        'dietary_tags_micro_f1': round(micro_f1, 4),",
                "        'dietary_tags_macro_f1': round(macro_f1, 4),",
                "        'components_token_f1': round(comp_f1_sum / total, 4),",
                "        'search_synonyms_token_f1': round(syn_f1_sum / total, 4),",
                "        'food_safety_violations': safety_violations,",
                "        'food_safety_violation_rate': round(safety_violations / total, 4),",
                "        'latency': {",
                "            'p50_ms': round(s_lat[len(s_lat)//2], 2),",
                "            'p95_ms': round(s_lat[int(len(s_lat)*0.95)], 2),",
                "            'mean_ms': round(sum(s_lat)/len(s_lat), 2),",
                "        },",
                "    }",
                "print('[3/7] Schemas Pydantic v2 e motor de avaliação carregados!', flush=True)",
            ]
        )
    )

